/**
 * LA table de vocabulaire de Humalis : tous les mots du langage, rangés en
 * un seul endroit. Le lexer (`src/lexer/motsCles.ts`), l'analyse des styles
 * (`src/analyse/styles.ts`), l'extension VS Code et le site de
 * documentation la lisent ; aucun d'eux ne garde sa propre liste.
 *
 * Ajouter un mot, c'est ajouter une entrée. Les tests de
 * `tests/vocabulaire/table.test.ts` vérifient sa forme, et compilent
 * l'exemple de chaque mot pris en charge.
 *
 * Honnêteté : seule la colonne `web` décrit du code produit et testé
 * aujourd'hui. Les colonnes `mobile`, `desktop`, `serveur` et `statique`
 * sont des intentions, reprises de la vision et du plan du vocabulaire.
 */
