/** Une valeur de style (« bleu », « grande ») : la classe CSS produite par la cible web. */
function valeurStyle(
  mot: string,
  valeurDe: readonly string[],
  variantes: readonly string[],
  description: string,
  exemple: string,
  accentue?: string,
): EntreeVocabulaire {
  return {
    mot,
    ...(accentue ? { accentue } : {}),
    variantes,
    categorie: 'valeurStyle',
    concept: `valeurStyle.${mot}`,
    contextes: ['valeurStyle'],
    valeurDe,
    cibles: ecran(
      `className="humalis-${valeurDe[0]}-${mot}"`,
      `StyleSheet (${valeurDe[0]} ${mot})`,
      `class="humalis-${valeurDe[0]}-${mot}"`,
      valeurDe.length > 1 ? `de même pour ${valeurDe.slice(1).join(' et ')}` : undefined,
    ),
    couvre: ['css'],
    description,
    exemple,
    statut: 'supporte',
    etape: 0,
  };
}

/** Un mot de liaison : marqué par le lexer, sauté par le parser (décision Q3). */
function liaison(mot: string, description: string, accentue?: string, elision = false): EntreeVocabulaire {
  return {
    mot,
    ...(accentue ? { accentue } : {}),
    variantes: [],
    categorie: 'liaison',
    concept: `liaison.${mot}`,
    contextes: [],
    ...(elision ? { elision: true } : {}),
    cibles: AUCUNE,
    couvre: [],
    description,
    exemple: PAGE('    variable stock = 0\n    si le stock est égal à 0 :\n        afficher "Rupture de stock"'),
    statut: 'supporte',
    etape: 0,
  };
}

