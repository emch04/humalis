/** Une sorte de champ, écrite après « champ » ou à sa place en tête de ligne (contexte « saisie »). */
function saisie(entree: {
  mot: string;
  accentue?: string;
  variantes?: string[];
  web: string;
  mobile: string;
  statique?: string;
  couvre: string[];
  description: string;
  ligne: string;
  note?: string;
}): EntreeVocabulaire {
  return {
    mot: entree.mot,
    ...(entree.accentue ? { accentue: entree.accentue } : {}),
    variantes: entree.variantes ?? [],
    categorie: 'saisie',
    concept: `saisie.${entree.mot.replace(/ /g, '_')}`,
    contextes: ['saisie'],
    cibles: ecran(entree.web, entree.mobile, entree.statique ?? entree.web),
    couvre: entree.couvre,
    description: entree.description,
    exemple: EN_FORMULAIRE(`        ${entree.ligne}`),
    statut: 'supporte',
    etape: 5,
    ...(entree.note ? { note: entree.note } : {}),
  };
}

