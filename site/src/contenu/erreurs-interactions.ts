/** Une page « accueil » avec un titre, puis les lignes données (décalées de quatre espaces). */
const page = (...lignes: string[]) => ['page "accueil" :', '    titre "Accueil"', ...lignes.map((l) => `    ${l}`)].join('\n');
/** Une page avec un bouton « Go » ; `lignes` vont dans son clic (décalées de huit espaces). */
const clic = (lignes: string[], avant: string[] = []) => page(...avant, 'bouton "Go"', 'quand l\'utilisateur clique sur "Go" :', ...lignes.map((l) => `    ${l}`));

