/**
 * Les messages des e-mails et des comptes invités : « emails par brevo »,
 * « invitations vers … », « mot de passe oublie vers … », « … comptes » et
 * « envoyer email … ». Rangés à part et ajoutés à la fin du catalogue
 * (`erreurs.ts`). Comme partout : aucun message n'est écrit ici, le site
 * affiche celui que produit le compilateur.
 */
import type { EntreeErreur, GroupeErreur } from './erreurs';

const e = (
  id: string,
  groupe: GroupeErreur,
  titre: string,
  explication: string,
  correction: string,
  fautif: string,
  corrige: string,
  motif: string,
  options: { gravite?: 'erreur' | 'avertissement'; sites?: number } = {},
): EntreeErreur => ({
  id, groupe, titre, explication, correction, fautif, corrige, motif,
  gravite: options.gravite ?? (groupe === 'avertissement' ? 'avertissement' : 'erreur'),
  sites: options.sites ?? 1,
  atteignable: true,
});

const PAGES = 'page "accueil" :\n    titre "Accueil"\n\npage "bienvenue" :\n    titre "Bienvenue"\n';

/** Un serveur avec les lignes données, et deux pages. */
const serveur = (...lignes: string[]) => ['serveur "boutique" :', ...lignes.map((l) => `    ${l}`), '', PAGES].join('\n');

/** Une donnée « message » et sa route ; `apres` va sous la route. */
const avecMessage = (avant: string[], regles: string[], apres: string[]) =>
  serveur(...avant, 'donnee message :', '    nom : texte', '    email : texte', 'route "messages" :', ...regles.map((r) => `    ${r}`), ...apres.map((l) => `    ${l}`));
const REGLES = ['seul admin peut lire message', 'seul admin peut modifier message', 'seul admin peut supprimer message', 'connecte peut creer message'];
const envoi = (ligne: string) => avecMessage(['emails par brevo'], REGLES, ['quand message est cree :', `    ${ligne}`]);
const BON_ENVOI = 'envoyer email aux admins avec sujet "Nouveau" et texte "{message.nom}"';

/** Une page qui fait une action au clic. */
const auClic = (lignesServeur: string[], action: string) =>
  serveur(...lignesServeur).replace('page "bienvenue" :', `page "action" :\n    titre "Action"\n    champ email "Adresse"\n    bouton "Go"\n    quand l'utilisateur clique sur "Go" :\n        ${action}\n\npage "bienvenue" :`);

/** Un serveur à trois données, sans aucun avertissement ; `champs` va dans « commande », `apres` sous sa route. */
const fichesAvecSuivi = (suivi: string[], champs: string[], apres: string[] = []) =>
  serveur(
    'donnee produit :', '    prix : nombre', '    commune : texte',
    'donnee commande :', ...champs.map((c) => `    ${c}`),
    'donnee suivi :', ...suivi.map((c) => `    ${c}`),
    'route "produits" :', '    seul admin peut lire produit', '    seul admin peut modifier produit',
    'route "suivis" :', '    seul admin peut lire suivi', '    seul admin peut modifier suivi',
    'route "commandes" :', '    seul admin peut lire commande', '    seul admin peut modifier commande',
    ...(apres.length > 0 ? ['    quand commande est cree :', ...apres.map((l) => `        ${l}`)] : []),
  );
const fiches = (champs: string[], apres: string[] = []) => fichesAvecSuivi(['etape : texte'], champs, apres);

/** Un serveur et une page qui envoie une commande. */
const pageEnvoi = (champs: string[], action: string) =>
  serveur('donnee commande :', ...champs.map((c) => `    ${c}`), 'route "commandes" :', '    tout le monde peut creer commande', '    seul admin peut lire commande', '    seul admin peut modifier commande')
    .replace('page "bienvenue" :', `page "action" :\n    titre "Action"\n    bouton "Go"\n    quand l'utilisateur clique sur "Go" :\n        ${action}\n\npage "bienvenue" :`);

/** Un serveur où « suivi » se lit par identifiant, et une page qui le lit. */
const pageSuivi = (action: string) =>
  serveur('donnee suivi :', '    etape : texte', 'route "suivis" :', '    tout le monde peut lire suivi par identifiant', '    seul admin peut modifier suivi')
    .replace('page "bienvenue" :', `page "action" :\n    titre "Action"\n    variable suivi = rien\n    bouton "Go"\n    quand l'utilisateur clique sur "Go" :\n        ${action}\n\npage "bienvenue" :`);

/** Une page où « lu » commence à rien. */
const programmeAjout = (action: string) =>
  `page "accueil" :\n    titre "A"\n    variable lu = rien\n    variable tous = ["a"]\n    bouton "Go"\n    quand l'utilisateur clique sur "Go" :\n        changer lu par "b"\n        ${action}\n`;

