/**
 * Les messages des e-mails et des comptes invités : « emails par brevo »,
 * « invitations vers … », « mot de passe oublie vers … », « … comptes » et
 * « envoyer email … ». Rangés à part et ajoutés à la fin du catalogue
 * (`erreurs.ts`). Comme partout : aucun message n'est écrit ici, le site
 * affiche celui que produit le compilateur.
 */
import type { EntreeErreur, GroupeErreur } from './erreurs';

const e = (
  id: string,
  groupe: GroupeErreur,
  titre: string,
  explication: string,
  correction: string,
  fautif: string,
  corrige: string,
  motif: string,
  options: { gravite?: 'erreur' | 'avertissement'; sites?: number; atteignable?: boolean } = {},
): EntreeErreur => ({
  id, groupe, titre, explication, correction, fautif, corrige, motif,
  gravite: options.gravite ?? (groupe === 'avertissement' ? 'avertissement' : 'erreur'),
  sites: options.sites ?? 1,
  atteignable: options.atteignable ?? true,
});

const PAGES = 'page "accueil" :\n    titre "Accueil"\n\npage "bienvenue" :\n    titre "Bienvenue"\n';

/** Un serveur avec les lignes données, et deux pages. */
const serveur = (...lignes: string[]) => ['serveur "boutique" :', ...lignes.map((l) => `    ${l}`), '', PAGES].join('\n');

/** Une donnée « message » et sa route ; `apres` va sous la route. */
const avecMessage = (avant: string[], regles: string[], apres: string[]) =>
  serveur(...avant, 'donnee message :', '    nom : texte', '    email : texte', 'route "messages" :', ...regles.map((r) => `    ${r}`), ...apres.map((l) => `    ${l}`));
const REGLES = ['seul admin peut lire message', 'seul admin peut modifier message', 'seul admin peut supprimer message', 'connecte peut creer message'];
const envoi = (ligne: string) => avecMessage(['emails par brevo'], REGLES, ['quand message est cree :', `    ${ligne}`]);
const BON_ENVOI = 'envoyer email aux admins avec sujet "Nouveau" et texte "{message.nom}"';

/** Une donnée séparée par groupe ; `regle` s'ajoute à ses règles. */
const separee = (regle: string) => serveur('roles client', 'donnee commande par boutique :', '    total : nombre', 'route "commandes" :', `    ${regle}`, ...(regle.includes('lire') ? [] : ['    client peut lire commande']), ...(regle.includes('creer') ? ['    seul admin peut modifier commande', '    seul admin peut supprimer commande'] : ['    seul admin peut modifier commande']));

/** Une route avec les lignes d'action données, et deux données pour tester une action mal placée. */
const actions = (lignes: string[]) => serveur('roles gerant', 'donnee commande :', '    total : nombre', 'donnee produit :', '    nom : texte', 'route "commandes" :', '    seul gerant peut lire commande', '    seul gerant peut modifier commande', ...lignes.map((l) => `    ${l}`), 'route "produits" :', '    seul gerant peut lire produit', '    seul gerant peut modifier produit');

/** Une page qui agit sur une fiche lue sur sa route. */
const PAGE_FICHE = (action: string) => `page "action" reservee a gerant sinon vers "bienvenue" :\n    variable liste = []\n    titre "Action"\n    quand la page se charge :\n        envoyer requete vers "commandes" dans liste\n    pour chaque c dans liste :\n        bouton "Go"\n        quand l'utilisateur clique sur "Go" :\n            ${action}\n\npage "bienvenue" :`;

/** Un serveur avec des documents. */
const documents = (lignes: string[]) => serveur('roles gerant', ...lignes, 'donnee commande :', '    total : nombre', 'donnee produit :', '    nom : texte', 'route "commandes" :', '    seul gerant peut lire commande', '    seul gerant peut modifier commande', 'route "produits" :', '    seul gerant peut lire produit', '    seul gerant peut modifier produit');
const avecDocument = (action: string) => documents(['document "a" de commande :', '    titre "T"']).replace('page "bienvenue" :', PAGE_FICHE(action));

/** Un serveur avec l'IA ; `lignes` va dans le serveur. */
const serveurIa = (lignes: string[], route: string[] = []) => serveur('roles gerant', ...lignes, 'donnee commande :', '    total : nombre', 'route "commandes" :', '    seul gerant peut lire commande', '    seul gerant peut modifier commande', ...route.map((l) => `    ${l}`));
const IA_OK = ['ia par anthropic', 'seul gerant peut demander a ia'];
const pageIa = (lignes: string[], action: string) => serveurIa(lignes).replace('page "bienvenue" :', `page "action" :\n    variable reponse = ""\n    titre "Action"\n    texte reponse\n    bouton "Go"\n    quand l'utilisateur clique sur "Go" :\n        ${action}\n\npage "bienvenue" :`);

/** Un serveur avec une donnée payable ; `apres` remplace la ligne « quand … est payee ». */
const QUAND_PAYEE = ['quand reservation est payee :', '    creer journal avec nom "x"'];
const serveurPaye = (entete: string[], apres: string[] = QUAND_PAYEE) => serveur('roles gerant', ...entete, 'donnee reservation :', '    total : nombre', '    nom : texte', 'donnee journal :', '    nom : texte', 'route "reservations" :', '    seul gerant peut lire reservation', '    seul gerant peut modifier reservation', ...apres.map((l) => `    ${l}`), 'route "journaux" :', '    seul gerant peut lire journal', '    seul gerant peut modifier journal');
const PAIEMENTS_OK = ['paiements par stripe'];
const pagePaye = (action: string, sansEvenement = false) => serveurPaye(PAIEMENTS_OK).replace('page "bienvenue" :', `page "action" reservee a gerant sinon vers "bienvenue" :\n    variable liste = []\n    titre "Action"\n    quand la page se charge :\n        envoyer requete vers "reservations" dans liste\n    pour chaque r dans liste :\n${sansEvenement ? `        ${action}` : `        bouton "Go"\n        quand l'utilisateur clique sur "Go" :\n            ${action}`}\n\npage "bienvenue" :`);

/** Une page qui lance une action. */
const avecAction = (action: string) => actions(['seul gerant peut faire "rembourser" sur commande :', '    refuser "Non"']).replace('page "bienvenue" :', PAGE_FICHE(action));

/** Une page qui fait une action au clic. */
const auClic = (lignesServeur: string[], action: string) =>
  serveur(...lignesServeur).replace('page "bienvenue" :', `page "action" :\n    titre "Action"\n    champ email "Adresse"\n    bouton "Go"\n    quand l'utilisateur clique sur "Go" :\n        ${action}\n\npage "bienvenue" :`);

/** Un serveur à trois données, sans aucun avertissement ; `champs` va dans « commande », `apres` sous sa route. */
const fichesAvecSuivi = (suivi: string[], champs: string[], apres: string[] = []) =>
  serveur(
    'donnee produit :', '    prix : nombre', '    commune : texte',
    'donnee commande :', ...champs.map((c) => `    ${c}`),
    'donnee suivi :', ...suivi.map((c) => `    ${c}`),
    'route "produits" :', '    seul admin peut lire produit', '    seul admin peut modifier produit',
    'route "suivis" :', '    seul admin peut lire suivi', '    seul admin peut modifier suivi',
    'route "commandes" :', '    seul admin peut lire commande', '    seul admin peut modifier commande',
    ...(apres.length > 0 ? ['    quand commande est cree :', ...apres.map((l) => `        ${l}`)] : []),
  );
const fiches = (champs: string[], apres: string[] = []) => fichesAvecSuivi(['etape : texte'], champs, apres);

